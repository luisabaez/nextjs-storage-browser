def get_column_mapping(entity_prefix, source):
    """
    Look up the column mapping for a given entity and source.

    Checks for a source-specific override first, then falls back to
    the default entity mapping.

    Args:
        entity_prefix: Entity prefix (e.g., "FIN_CUSTOMER", "HCM_PERSON")
        source: Source agency (e.g., "PRIFAS", "HACIENDA")

    Returns:
        dict with 'csv_columns' and 'sql_columns', or None if no mapping
        is registered (caller should use dynamic fallback).
    """
    entity_prefix = entity_prefix.upper()
    source = source.upper()

    # Check source-specific override first
    source_key = f"{entity_prefix}|{source}"
    if source_key in COLUMN_REGISTRY:
        return COLUMN_REGISTRY[source_key]

    # Fall back to default entity mapping
    if entity_prefix in COLUMN_REGISTRY:
        return COLUMN_REGISTRY[entity_prefix]

    # No mapping registered - caller uses dynamic fallback
    return None


def register_mapping(entity_prefix, csv_columns, sql_columns, source=None):
    """
    Programmatically register a column mapping.

    Args:
        entity_prefix: Entity prefix (e.g., "FIN_GL_BALANCES")
        csv_columns: list of CSV header names
        sql_columns: list of SQL column names (same length as csv_columns)
        source: Optional source for a source-specific override

    Raises:
        ValueError: if csv_columns and sql_columns have different lengths
    """
    if len(csv_columns) != len(sql_columns):
        raise ValueError(
            f"csv_columns ({len(csv_columns)}) and sql_columns ({len(sql_columns)}) "
            f"must have the same length"
        )

    key = entity_prefix.upper()
    if source:
        key = f"{key}|{source.upper()}"

    COLUMN_REGISTRY[key] = {
        "csv_columns": csv_columns,
        "sql_columns": sql_columns,
    }


def auto_mapping_from_headers(headers):
    """
    Generate a mapping dict from raw CSV headers by sanitizing them.

    Useful for building a mapping from the first file encountered,
    so it can be reviewed and added to COLUMN_REGISTRY.

    Args:
        headers: list of CSV header strings

    Returns:
        dict with 'csv_columns' (original headers) and
        'sql_columns' (sanitized versions)
    """
    return {
        "csv_columns": list(headers),
        "sql_columns": [sanitize_column_name(h) for h in headers],
    }
